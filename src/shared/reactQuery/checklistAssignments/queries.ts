import {REFETCH_MODES} from '@/shared/constants/reactQuery/general';
import {CHECKLIST_ASSIGNMENTS} from '@/shared/constants/reactQueryConstants';
import {useQueryHandler} from '@/shared/hooks/reactQuery/useQueryHandler';
import {UseQueryHandlerProps} from '@/shared/interfaces/hooks';

export const useQueries = () => {
  return {
    useFetchChecklistAssignmentsList: ({
      callBackFuncs,
      params,
      enabled,
      toastConfig,
    }: UseQueryHandlerProps = {}) =>
      useQueryHandler({
        queryKey: CHECKLIST_ASSIGNMENTS.fetchChecklistAssignmentsList.queryKey,
        endpoint: CHECKLIST_ASSIGNMENTS.fetchChecklistAssignmentsList.endpoint({
          params,
        }),
        params,
        refetchConfig: {mode: REFETCH_MODES.STATIC},
        enabled,
        callbacks: {...callBackFuncs},
        mergedToastConfig: {
          toastConfigAlways: {error: {show: true}},
          toastConfig,
        },
      }),
  };
};
